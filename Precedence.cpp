#include <iostream>
using namespace std;
int main() {

    // Constant in C++// Constant in C++ is a variable whose value cannot be changed once it is assigned.
    int a = 50;
    cout << "The value of a was: " << a << endl;
    a = 100;
    cout << "The value of a is :" <<  a << endl;

    return 0;
}